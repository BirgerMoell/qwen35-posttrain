#!/usr/bin/env python3
"""Build OpenEuroLLM Reasoning-Instruct: a public messages-format dataset plus the matching
pre-tokenized Stage-2 training mix (v2 chat template), in one pass so they cannot drift.

Reasoning rows store the trace in `reasoning_content` (final assistant turn only; earlier turns
carry none). Every admitted row is rendered with the v2 template and audited: reasoning rows have
one prompt-side <think>, one supervised </think>, a nonempty trace and answer; direct rows have no
think token at all; nothing exceeds --max-length (rejected, never truncated). Rows whose
assistant text names another assistant/lab without the prompt mentioning it are dropped.

Per-source budgets are rendered-token targets. Pass A estimates each source's size from character
counts; pass B keeps rows whose id hash falls under budget/size, so selection is deterministic.
"""
from __future__ import annotations

import argparse
from collections import Counter
from concurrent.futures import ProcessPoolExecutor, as_completed
import json
import re
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq
from jinja2 import TemplateError

from audit_two_stage_sft import source_kind
from build_oellm_excellent_stage1 import THINK_IDS, file_sha256, get_tokenizer
from build_oellm_stage1_mix import SCHEMA as TOKEN_SCHEMA, SplitWriter, h64
from build_oellm_stage2_reasoning_pool import normalize

THINK_OPEN, THINK_CLOSE = 18, 17
CHARS_PER_TOKEN = 3.3
DOLCI_TR_LANGS = ("cs", "de", "el", "es", "fi", "fr", "it", "nl", "pl", "ro", "sv", "uk")
TARGETS = {"bg", "cs", "da", "de", "el", "en", "es", "et", "fi", "fr", "ga", "hr", "hu", "it", "lt", "lv", "mt", "nl",
           "pl", "pt", "ro", "sk", "sl", "sv", "ca", "eu", "gl", "bs", "ka", "mk", "sq", "sr", "tr", "uk", "is", "no", "nb", "nn"}
FOREIGN = re.compile(r"\b(?:OpenAI|ChatGPT|GPT-?(?:3(?:\.5)?|4(?:o|\.\d)?|5)|Anthropic|Qwen|Tongyi|DeepSeek|Mistral AI|"
                     r"Meta AI|SmolLM|OLMo|Olmo|Ai2|AI2|AllenAI|Allen Institute)\b")
WRAPPED = re.compile(r"^\s*<(AnswerGeneration|Answer|answer|response|Response)>\s*(.*?)\s*</\1>\s*$", re.S)

# Rendered-token budgets (train). "all" = keep every valid row.
BUDGET = {
    "excellent:nemotron/multilingual_de": 75e6, "excellent:nemotron/multilingual_es": 75e6,
    "excellent:nemotron/multilingual_fr": 75e6, "excellent:nemotron/multilingual_it": 75e6,
    "excellent:smoltalk2/OpenThoughts3_1.2M_think": 150e6, "excellent:nemotron/chat": 100e6,
    "excellent:smoltalk2/smoltalk_multilingual8_Qwen3_32B_think": 100e6,
    **{f"dolci_tr:{lang}": 45e6 for lang in DOLCI_TR_LANGS},
    "dolci32b:Persona Precise IF": 90e6, "dolci32b:Dolci Think Precise IF": 60e6,
    "dolci32b:WildJailbreak": "all", "dolci32b:WildGuardMix": "all", "dolci32b:CoCoNot": "all",
    "dolci32b:Wildchat": 100e6, "dolci32b:OpenAssistant": "all", "dolci32b:TableGPT": "all",
    "dolci32b:SYNTHETIC-2-SFT-Verified": 40e6, "dolci32b:Dolci Think OpenThoughts3 Math": 30e6,
    "dolci32b:Dolci Think Python Algorithms": 30e6, "dolci32b:Nemotron Code": 15e6,
    "dolci32b:Dolci Think OpenThoughts3 Code": 15e6, "dolci32b:Dolci Think OpenThoughts3 STEM": 20e6,
    "dolci32b:Aya": 20e6, "dolci32b:Olmo Identity Hardcoded Data": 0,
    "ml_traces": "all", "medqa": "all", "kimi_sv": "all",
}
LICENSE = {
    "excellent:nemotron": "CC-BY-4.0 (NVIDIA Nemotron-Post-Training-Dataset-v2; source-specific exceptions apply)",
    "excellent:smoltalk2": "Apache-2.0 (SmolTalk2; inherited subsets keep their upstream licenses)",
    "dolci_tr": "Apache-2.0 (openeurollm/Dolci-Think-SFT-translated; upstream allenai/Dolci-Think-SFT-32B is ODC-BY-1.0)",
    "dolci32b": "ODC-BY-1.0 (allenai/Dolci-Think-SFT-32B via openeurollm decontaminated copy)",
    "ml_traces": "CC-BY-4.0 (openeurollm/reasoning-traces-multilingual)",
    "medqa": "MIT (MedQA, Jin et al. 2021); reasoning traces generated by Kimi-K3, model output terms apply",
    "kimi_sv": "Apache-2.0 (jonasaise/kimi-kr-synth-sv); generated by Kimi-K3, model output terms apply",
    "replay:excellent": "Mixed upstream terms (openeurollm/OpenEuroLLM-Excellent-SFT)",
    "replay:dolci_tr": "Apache-2.0 (openeurollm/Dolci-Instruct-SFT-translated)",
    "replay:aya": "Apache-2.0 (CohereLabs/aya_dataset)",
    "replay:identity": "CC-BY-4.0 (OpenEuroLLM model identity)",
}
MSG = pa.list_(pa.struct([("role", pa.string()), ("content", pa.string()), ("reasoning_content", pa.string())]))
DATA_SCHEMA = pa.schema([("id", pa.string()), ("mode", pa.string()), ("source", pa.string()), ("source_dataset", pa.string()),
                         ("license", pa.string()), ("language", pa.string()), ("messages", MSG)])


def license_for(group: str) -> str:
    for key in sorted(LICENSE, key=len, reverse=True):
        if group.startswith(key):
            return LICENSE[key]
    raise KeyError(group)


# ---------- row iterators: yield (split, group, language, id, source_dataset, messages) ----------

def rows_dolci_tr(path: str, lang: str):
    for b in pq.ParquetFile(path).iter_batches(batch_size=512, columns=["id", "messages", "filter_pass"]):
        for r in b.to_pylist():
            if not r["filter_pass"] or DOLCI_TR_LANGS[h64(r["id"]) % len(DOLCI_TR_LANGS)] != lang:
                continue  # one language per source family
            yield ("validation" if h64(r["id"] + "#v") % 1000 == 0 else "train", f"dolci_tr:{lang}", lang,
                   f"dolci_tr:{lang}:{r['id']}", "openeurollm/Dolci-Think-SFT-translated@b877863a", r["messages"])


def rows_dolci32b(path: str):
    for b in pq.ParquetFile(path).iter_batches(batch_size=512, columns=["id", "messages", "source"]):
        for r in b.to_pylist():
            yield ("validation" if h64(r["id"] + "#v") % 1000 == 0 else "train", f"dolci32b:{r['source']}",
                   "mixed" if r["source"] == "Aya" else "en", f"dolci32b:{r['id']}",
                   "openeurollm/Dolci-Think-SFT-32B-decontaminated@286dde7d", r["messages"])


def rows_ml_traces(path: str):
    for r in pq.read_table(path, columns=["id", "messages", "language", "quality"]).to_pylist():
        if not (r["quality"] or {}).get("accepted") or r["language"] not in TARGETS:
            continue
        yield ("validation" if h64(r["id"] + "#v") % 50 == 0 else "train", "ml_traces", r["language"],
               f"ml_traces:{r['id']}", "openeurollm/reasoning-traces-multilingual@031163d3", r["messages"])


def rows_medqa(path: str):
    for r in pq.read_table(path).to_pylist():
        if not (r["correct"] and r.get("finish_reason") == "stop" and r["reasoning"] and r["response"]):
            continue
        options = "\n".join(f"{k}. {v}" for k, v in sorted((r["options"] or {}).items()) if v)
        prompt = f"{r['question'].strip()}\n\n{options}"
        yield ("validation" if h64(r["question_id"] + "#v") % 100 == 0 else "train", "medqa", "en",
               f"medqa:{r['question_id']}", "birgermoell/medqa-reasoning-traces@82fe04a7",
               [{"role": "user", "content": prompt},
                {"role": "assistant", "content": f"<think>\n{r['reasoning'].strip()}\n</think>\n\n{r['response'].strip()}"}])


def rows_kimi_sv(path: str):
    """Swedish Kimi-K3 data: rows with a trace are reasoning rows, the rest direct answers."""
    with open(path, encoding="utf-8") as stream:
        for i, line in enumerate(stream):
            r = json.loads(line)
            prompt, trace, answer = (r["original_prompt"] or "").strip(), (r["generated_trace"] or "").strip(), (r["final_response"] or "").strip()
            if not prompt or not answer:
                continue
            content = f"<think>\n{trace}\n</think>\n\n{answer}" if trace else answer
            rid = f"kimi_sv:{h64(prompt):016x}"
            yield ("validation" if h64(rid + "#v") % 100 == 0 else "train", "kimi_sv", "sv", rid,
                   "jonasaise/kimi-kr-synth-sv@c8016177", [{"role": "user", "content": prompt}, {"role": "assistant", "content": content}])


def iter_unit(unit: dict):
    kind, path = unit["kind"], unit["path"]
    if kind == "dolci_tr":
        yield from rows_dolci_tr(path, unit["language"])
    elif kind == "dolci32b":
        yield from rows_dolci32b(path)
    elif kind == "ml_traces":
        yield from rows_ml_traces(path)
    elif kind == "medqa":
        yield from rows_medqa(path)
    elif kind == "kimi_sv":
        yield from rows_kimi_sv(path)
    else:
        raise ValueError(kind)


def text_chars(messages) -> int:
    return sum(len(m.get("content") or "") for m in messages)


def size_pass(unit: dict) -> dict:
    c: Counter[str] = Counter()
    for split, group, *_rest, messages in iter_unit(unit):
        if split == "train":
            c[group] += text_chars(messages)
    return dict(c)


# ---------- render + audit ----------

def admit(messages, mode, tokenizer, max_length):
    """Return (normalized messages, ids, mask, n_target) or raise ValueError."""
    if mode == "reasoning":
        if source_kind(messages) != "reasoning":
            raise ValueError("not a reasoning row")
        normalized = normalize(messages)
    else:
        if source_kind(messages) != "direct":
            raise ValueError("not a direct row")
        normalized = [{"role": m["role"], "content": m["content"]} for m in messages]
    if any("<image>" in m["content"] for m in normalized if m["role"] == "user"):
        raise ValueError("image placeholder")
    answer = "\n".join((m["content"] + "\n" + (m.get("reasoning_content") or "")) for m in normalized if m["role"] == "assistant")
    context = "\n".join(m["content"] for m in normalized if m["role"] != "assistant")
    if FOREIGN.search(answer) and not FOREIGN.search(context):
        raise LookupError("foreign assistant identity")
    r = tokenizer.apply_chat_template(normalized, tokenize=True, add_generation_prompt=False,
                                      return_dict=True, return_assistant_tokens_mask=True)
    ids, mask = list(r["input_ids"]), r.get("assistant_masks")
    if mask is None or len(ids) != len(mask) or not 0 < sum(mask) < len(mask) or mask[0]:
        raise ValueError("invalid mask")
    target = [t for t, a in zip(ids, mask) if a]
    if THINK_OPEN in target:
        raise RuntimeError("FATAL: supervised <think>")
    if mode == "reasoning":
        if ids.count(THINK_OPEN) != 1 or ids.count(THINK_CLOSE) != 1 or target.count(THINK_CLOSE) != 1:
            raise ValueError("think structure")
    elif any(t in THINK_IDS for t in target):
        raise RuntimeError("FATAL: direct row supervises a think token")
    if len(ids) > max_length:
        raise OverflowError("overlength")
    return normalized, ids, mask, len(target)


def to_record(rid, mode, group, source_dataset, language, normalized):
    return {"id": rid, "mode": mode, "source": group, "source_dataset": source_dataset, "license": license_for(group),
            "language": language, "messages": [{"role": m["role"], "content": m["content"],
                                                "reasoning_content": m.get("reasoning_content")} for m in normalized]}


def tok_record(rid, group, language, ids, mask, n):
    return {"input_ids": ids, "assistant_masks": [int(v) for v in mask], "source": group, "language": language,
            "id": rid, "supervised_tokens": n}


def build_unit(unit: dict, cfg: dict, keep_prob: dict) -> dict:
    tok = get_tokenizer(cfg["tokenizer"], cfg["template"])
    out_d, out_t = Path(cfg["dataset_dir"]) / "data", Path(cfg["mix_dir"])
    name = unit["name"]
    dw = {s: SplitWriter(out_d, s, name, batch_rows=500, schema=DATA_SCHEMA) for s in ("train", "validation")}
    tw = {s: SplitWriter(out_t, s, name, batch_rows=500, schema=TOKEN_SCHEMA) for s in ("train", "validation")}
    c: dict[str, Counter] = {}

    def emit(split, mode, group, language, rid, source_dataset, messages, copies=1):
        k = c.setdefault(group, Counter())
        try:
            normalized, ids, mask, n = admit(messages, mode, tok, cfg["max_length"])
        except LookupError:
            k["drop_foreign_identity"] += 1
            return
        except OverflowError:
            k["drop_overlength"] += 1
            return
        except (KeyError, TypeError, ValueError, TemplateError):
            k["drop_invalid"] += 1
            return
        dw[split].add(to_record(rid, mode, group, source_dataset, language, normalized))
        for _ in range(copies):
            tw[split].add(tok_record(rid, group, language, ids, mask, n))
        k[f"{split}_rows"] += 1
        k[f"{split}_tokens"] += len(ids) * copies

    if unit["kind"] == "excellent_pool":
        t = pq.read_table(unit["path"], columns=["id", "source", "language", "messages_json", "input_ids"])
        for rid, src, lang, mj in zip(t["id"].to_pylist(), t["source"].to_pylist(), t["language"].to_pylist(),
                                      t["messages_json"].to_pylist()):
            group = f"excellent:{src}"
            p = keep_prob.get(group, 1.0)
            if unit["split"] == "train" and h64(rid) / 2**64 >= p:
                continue
            msgs = json.loads(mj)
            last = msgs[-1]  # re-inline so admit() re-runs the same normalization and audit
            msgs[-1] = {"role": "assistant", "content": f"<think>\n{last['reasoning_content']}\n</think>\n\n{last['content']}"}
            emit(unit["split"], "reasoning", group, lang, f"excellent:{rid}",
                 "openeurollm/OpenEuroLLM-Excellent-SFT@c4ee5580", msgs)
    elif unit["kind"] == "replay":
        for b in pq.ParquetFile(unit["path"]).iter_batches(batch_size=1024):
            for r in b.to_pylist():
                identity = r["source"] in ("identity", "identity_v2")
                if not identity and h64(r["id"]) / 2**64 >= cfg["replay_fraction"]:
                    continue
                msgs = []
                for m in r["messages"]:
                    content = m["content"]
                    if m["role"] == "assistant" and (w := WRAPPED.match(content)):
                        content = w.group(2)
                    msgs.append({"role": m["role"], "content": content})
                kind = ("identity" if identity else "excellent" if r["source"].startswith("openeurollm/")
                        else r["source"])
                emit(unit["split"], "direct", f"replay:{kind}", r["language"], f"replay:{r['id']}",
                     "birgermoell/openeurollm-instruct-sft-v1", msgs,
                     copies=cfg["identity_exposures"] if identity and unit["split"] == "train" else 1)
    else:
        for split, group, lang, rid, sd, msgs in iter_unit(unit):
            if BUDGET.get(group, 0) == 0:
                c.setdefault(group, Counter())["excluded_by_budget"] += 1
                continue
            if split == "train" and h64(rid) / 2**64 >= keep_prob.get(group, 1.0):
                continue
            last = msgs[-1]["content"]
            mode = "reasoning" if "<think>" in last else "direct"
            emit(split, mode, group if mode == "reasoning" else f"{group}:direct", lang, rid, sd, msgs)
    files = []
    for writers in (dw, tw):
        for w in writers.values():
            if info := w.finish():
                files.append(info)
    return {"unit": name, "counts": {k: dict(v) for k, v in c.items()}, "files": files}


def plan(a) -> list[dict]:
    units = []
    for p in sorted(a.pool_dir.glob("*.parquet")):
        units.append({"kind": "excellent_pool", "path": str(p), "split": p.name.split("-")[0], "name": f"excellent-{p.stem}"})
    for lang in DOLCI_TR_LANGS:
        for p in sorted((a.staging / "Dolci-Think-SFT-translated" / lang).glob("*.parquet")):
            units.append({"kind": "dolci_tr", "language": lang, "path": str(p), "name": f"dolci_tr-{lang}-{p.stem}"})
    for p in sorted((a.staging / "Dolci-Think-SFT-32B-decontaminated" / "data").glob("*.parquet")):
        units.append({"kind": "dolci32b", "path": str(p), "name": f"dolci32b-{p.stem}"})
    for p in sorted((a.staging / "reasoning-traces-multilingual" / "data").glob("*.parquet")):
        units.append({"kind": "ml_traces", "path": str(p), "name": f"ml_traces-{p.stem}"})
    for p in sorted((a.staging / "medqa-reasoning-traces" / "data").glob("train-*.parquet")):
        units.append({"kind": "medqa", "path": str(p), "name": f"medqa-{p.stem}"})
    for p in sorted((a.staging / "kimi-kr-synth-sv").glob("*.jsonl")):
        units.append({"kind": "kimi_sv", "path": str(p), "name": f"kimi_sv-{p.stem}"})
    for p in sorted((a.instruct_dir / "data").glob("*.parquet")):
        units.append({"kind": "replay", "path": str(p), "split": p.name.split("-")[0], "name": f"replay-{p.stem}"})
    return units


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pool-dir", type=Path, required=True)
    ap.add_argument("--staging", type=Path, required=True)
    ap.add_argument("--instruct-dir", type=Path, required=True)
    ap.add_argument("--tokenizer", type=Path, required=True)
    ap.add_argument("--template", type=Path, required=True)
    ap.add_argument("--dataset-dir", type=Path, required=True)
    ap.add_argument("--mix-dir", type=Path, required=True)
    ap.add_argument("--replay-fraction", type=float, default=0.25)
    ap.add_argument("--identity-exposures", type=int, default=2)
    ap.add_argument("--max-length", type=int, default=32768)
    ap.add_argument("--workers", type=int, default=8)
    a = ap.parse_args()
    get_tokenizer(str(a.tokenizer), str(a.template))
    (a.dataset_dir / "data").mkdir(parents=True, exist_ok=True)
    a.mix_dir.mkdir(parents=True, exist_ok=True)
    cfg = {"tokenizer": str(a.tokenizer), "template": str(a.template), "dataset_dir": str(a.dataset_dir),
           "mix_dir": str(a.mix_dir), "max_length": a.max_length, "replay_fraction": a.replay_fraction,
           "identity_exposures": a.identity_exposures}
    units = plan(a)
    # Pass A: size estimates (characters) for budgeted sources outside the pre-tokenized pool.
    sizes: Counter[str] = Counter()
    with ProcessPoolExecutor(a.workers) as pool:
        for r in pool.map(size_pass, [u for u in units if u["kind"] in ("dolci_tr", "dolci32b")]):
            sizes.update(r)
    pool_manifest = json.loads((a.pool_dir / "manifest.json").read_text())
    est_tokens = {g: n / CHARS_PER_TOKEN for g, n in sizes.items()}
    est_tokens.update({f"excellent:{s}": v.get("train_rendered_tokens", 0) for s, v in pool_manifest["by_source"].items()})
    keep_prob = {}
    for group, budget in BUDGET.items():
        if budget == "all" or group not in est_tokens:
            keep_prob[group] = 1.0
        else:
            keep_prob[group] = min(1.0, budget / max(est_tokens[group], 1.0))
    print("keep probabilities:", json.dumps({k: round(v, 4) for k, v in sorted(keep_prob.items())}), flush=True)
    # Pass B: normalize, audit, render, write both outputs.
    counts: dict[str, Counter] = {}
    files = []
    with ProcessPoolExecutor(a.workers) as pool:
        jobs = [pool.submit(build_unit, u, cfg, keep_prob) for u in units]
        for i, f in enumerate(as_completed(jobs), 1):
            r = f.result()
            for g, c in r["counts"].items():
                counts.setdefault(g, Counter()).update(c)
            files.extend(r["files"])
            if i % 100 == 0:
                print(f"{i}/{len(jobs)} units", flush=True)
    by_group = {g: dict(c) for g, c in sorted(counts.items())}
    totals = Counter()
    for g, c in counts.items():
        mode = "direct" if g.startswith("replay:") or g.endswith(":direct") else "reasoning"
        for k in ("train_rows", "train_tokens", "validation_rows", "validation_tokens"):
            totals[f"{mode}_{k}"] += c.get(k, 0)
    hashes = {"template_sha256": file_sha256(a.template), "tokenizer_json_sha256": file_sha256(a.tokenizer / "tokenizer.json")}
    manifest = {"name": "openeurollm-reasoning-instruct", "version": "1.0.0", **hashes, "config": {**cfg, **hashes},
                "budgets": {k: v for k, v in BUDGET.items()}, "keep_probability": keep_prob,
                "totals": dict(totals), "by_source": by_group}
    for d, kind in ((a.dataset_dir, "openeurollm_reasoning_instruct_dataset"), (a.mix_dir, "stage2_reasoning_mix_pretokenized")):
        m = dict(manifest, kind=kind, files=[f for f in files if f["path"].startswith(str(d))])
        (d / "manifest.json").write_text(json.dumps(m, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps({"totals": dict(totals)}, indent=1))
    for g, c in by_group.items():
        print(f"  {g:<60} {c}")


if __name__ == "__main__":
    main()
